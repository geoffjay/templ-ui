// Generates daisyui/safelist.css: a Tailwind v4 `@source inline(...)` list of
// every class templ-ui components can render. Consumers import it so their
// Tailwind + daisyUI build emits those classes even though the component
// sources live in the Go module cache (which Tailwind never scans) and many
// daisyUI modifiers are assembled at runtime (e.g. "btn-" + cfg.Color).
//
// Two sources, both derived — nothing is hand-maintained:
//
//  1. Literal classes: Tailwind is run over the component .templ sources only
//     (`source(none)` + explicit @source globs) and every class it emitted is
//     read back from the output. This yields exactly the candidates Tailwind
//     recognises, with no false positives from arbitrary string literals.
//  2. Runtime-built modifiers: the Go sources are searched for class prefixes
//     passed to classFor("<prefix>", …) or concatenated as "<prefix>-" + v,
//     and each prefix is expanded against every class daisyUI itself defines
//     (node_modules/daisyui/daisyui.css) — so a new daisyUI modifier or a new
//     component prefix is picked up by re-running this script.
//
// Run with `bun run safelist` after changing component classes or bumping
// daisyUI; CI fails when the committed file is stale.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const componentDirs = ["daisyui", "containers", "shiki"];
const outFile = join(root, "daisyui", "safelist.css");

// Class names referenced by a stylesheet, CSS escapes removed.
function classesIn(css: string): Set<string> {
  const out = new Set<string>();
  for (const m of css.matchAll(/\.((?:\\.|[A-Za-z0-9_-])+)/g)) {
    out.add(m[1].replace(/\\(.)/g, "$1"));
  }
  return out;
}

function templSources(): string[] {
  const files: string[] = [];
  for (const dir of componentDirs) {
    for (const f of readdirSync(join(root, dir))) {
      if (f.endsWith(".templ")) files.push(join(root, dir, f));
    }
  }
  return files;
}

// 1. Literal classes detected by Tailwind in the component sources.
async function literalClasses(): Promise<Set<string>> {
  const tmp = join(root, "tmp", "safelist");
  mkdirSync(tmp, { recursive: true });
  const input = join(tmp, "input.css");
  const output = join(tmp, "output.css");
  writeFileSync(
    input,
    [
      '@import "tailwindcss" source(none);',
      ...componentDirs.map((d) => `@source "../../${d}/*.templ";`),
      '@plugin "daisyui";',
      "",
    ].join("\n"),
  );
  const proc = Bun.spawnSync(["bunx", "tailwindcss", "-i", input, "-o", output], {
    cwd: root,
    stderr: "pipe",
  });
  if (proc.exitCode !== 0) {
    throw new Error(`tailwindcss failed:\n${proc.stderr.toString()}`);
  }
  const classes = classesIn(readFileSync(output, "utf8"));
  rmSync(tmp, { recursive: true, force: true });
  return classes;
}

// 2. daisyUI modifiers for every prefix the components build at runtime.
function dynamicClasses(): Set<string> {
  const prefixes = new Set<string>();
  for (const file of templSources()) {
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(/classFor\("([a-z][a-z-]*)"/g)) prefixes.add(m[1]);
    for (const m of src.matchAll(/"([a-z][a-z-]*)-"\s*\+/g)) prefixes.add(m[1]);
  }
  const daisy = classesIn(readFileSync(join(root, "node_modules", "daisyui", "daisyui.css"), "utf8"));
  const out = new Set<string>();
  for (const cls of daisy) {
    for (const p of prefixes) {
      if (cls.startsWith(`${p}-`)) out.add(cls);
    }
  }
  return out;
}

const all = new Set([...(await literalClasses()), ...dynamicClasses()]);
// Brace, quote, and comma characters are @source inline() syntax; no real
// class contains them, but guard so a malformed token can't break the file.
const tokens = [...all].filter((c) => !/[{}",\s]/.test(c)).sort();

// One @source inline() line per leading segment keeps diffs reviewable.
const groups = new Map<string, string[]>();
for (const t of tokens) {
  const key = t.replace(/^[^:]*:/, "").split("-")[0];
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key)!.push(t);
}

const lines = [
  "/* Code generated by scripts/safelist.ts — DO NOT EDIT.",
  "",
  "   Every class templ-ui components can render, for Tailwind v4 + daisyUI 5",
  "   builds. Import it from your stylesheet after the daisyUI plugin:",
  "",
  '       @import "path/to/templ-ui/daisyui/safelist.css";',
  "",
  "   See docs/USAGE.md for locating the file inside the Go module cache. */",
  "",
  ...[...groups.keys()].sort().map((k) => `@source inline("${groups.get(k)!.join(" ")}");`),
  "",
];
writeFileSync(outFile, lines.join("\n"));
console.log(`safelist: ${tokens.length} classes in ${groups.size} groups -> daisyui/safelist.css`);
